"""Critical-net report for the routed board -> docs/critical_nets.md
USB pair, crystal, buck switch node / hot loop, IMU SPI buses, BMP581 vent area, IMU-to-inductor
distance. Runs in KiCad's Python."""
import os, math, pcbnew
from collections import defaultdict
HERE = os.path.dirname(os.path.abspath(__file__))
b = pcbnew.LoadBoard(os.path.join(HERE, "kicad", "fc.kicad_pcb"))
tomm = pcbnew.ToMM
L = {pcbnew.F_Cu: "F", pcbnew.In1_Cu: "In1", pcbnew.In2_Cu: "In2", pcbnew.In3_Cu: "In3", pcbnew.In4_Cu: "In4", pcbnew.B_Cu: "B"}

def net_stats(name):
    nc = b.FindNet(name).GetNetCode()
    length = defaultdict(float); vias = 0; widths = set()
    for t in b.GetTracks():
        if t.GetNetCode() != nc:
            continue
        if t.GetClass() == "PCB_VIA":
            vias += 1
        else:
            length[L[t.GetLayer()]] += tomm(t.GetLength()); widths.add(round(tomm(t.GetWidth()), 3))
    return sum(length.values()), dict(length), vias, sorted(widths)

def pos(ref, pad=None):
    fp = b.FindFootprintByReference(ref)
    p = fp.GetPosition() if pad is None else next(x for x in fp.Pads() if x.GetNumber() == pad).GetPosition()
    return tomm(p.x), tomm(p.y)

out = ["# Critical nets (from the routed board)", "",
       "Generated by `scripts/check_critical.py`. Lengths are routed copper only (pads excluded).", ""]
out += ["| Net | Routed length (mm) | By layer | Vias | Widths (mm) |", "|---|---|---|---|---|"]
groups = [("USB", ["USB_DP", "USB_DM", "USB_DP_C", "USB_DM_C"]),
          ("Crystal", ["HSE_IN", "HSE_OUT"]),
          ("Buck", ["BUCK_SW", "BUCK_BOOT", "BUCK_FB", "BUCK_COMP", "VBAT", "+5V"]),
          ("IMU0 SPI1", ["SPI1_SCK", "SPI1_SCK_MCU", "SPI1_MISO", "SPI1_MOSI", "IMU1_CS", "IMU1_DRDY", "IMU_CLKIN"]),
          ("IMU1 SPI2", ["SPI2_SCK", "SPI2_MISO", "SPI2_MOSI", "BMI_ACC_CS", "BMI_GYRO_CS"]),
          ("SDMMC2", ["SD_CLK", "SD_CLK_MCU", "SD_CMD", "SD_D0", "SD_D1", "SD_D2", "SD_D3"]),
          ("CAN1", ["CAN1_H", "CAN1_L"]), ("CAN2", ["CAN2_H", "CAN2_L"])]
names = {b.GetNetInfo().GetNetItem(i).GetNetname() for i in range(b.GetNetCount())}
for g, nets in groups:
    for n in nets:
        if n not in names:
            continue
        tot, by, v, w = net_stats(n)
        out.append(f"| {g}: `{n}` | {tot:.1f} | {', '.join(f'{k} {x:.1f}' for k, x in by.items())} | {v} | {', '.join(map(str, w))} |")
out.append("")
# pair skew
for a, c in [("USB_DP", "USB_DM"), ("USB_DP_C", "USB_DM_C"), ("CAN1_H", "CAN1_L"), ("CAN2_H", "CAN2_L")]:
    if a in names and c in names:
        out.append(f"- `{a}`/`{c}` length difference: {abs(net_stats(a)[0] - net_stats(c)[0]):.2f} mm")
# distances
imus = [pos("U20"), pos("U21")]
for ref in ("L1", "U1"):
    d = min(math.dist(pos(ref), p) for p in imus)
    out.append(f"- Nearest IMU to {ref} ({'buck inductor' if ref == 'L1' else 'buck IC'}): {d:.1f} mm (spec: ≥ 10 mm)")
d = math.dist(pos("Y1"), pos("U10", "12"))
out.append(f"- Crystal Y1 to MCU OSC_IN pin: {d:.1f} mm")
# copper under the BMP581 (other than its own pads), any layer
fp = b.FindFootprintByReference("U22")
bb = fp.GetBoundingBox(False, False)
under = defaultdict(int)
for t in b.GetTracks():
    if t.GetNetCode() == 0:
        continue
    if bb.Intersects(t.GetBoundingBox()):
        own = t.GetNetname() in {p.GetNetname() for p in fp.Pads()}
        lay = "via" if t.GetClass() == "PCB_VIA" else L[t.GetLayer()]
        under[(lay, "own net" if own else "other net")] += 1
out.append(f"- Tracks/vias inside the BMP581 body outline: {dict(under) if under else 'none'}")
# sensor nets under the buck switch node / inductor
sw = b.FindFootprintByReference("L1").GetBoundingBox(False, False)
sens = ("SPI", "IMU", "BMI", "I2C4", "HSE", "BARO")
bad = sorted({t.GetNetname() for t in b.GetTracks() if sw.Intersects(t.GetBoundingBox()) and t.GetNetname().startswith(sens)})
out.append(f"- Sensor/clock nets crossing the inductor L1 outline on any layer: {', '.join(bad) if bad else 'none'}")
# hot loop: input caps, IC, diode positions
try:
    pts = {r: pos(r) for r in ("U1", "D3", "C6", "C7", "C8")}
    span = max(math.dist(pts[a], pts[c]) for a in pts for c in pts)
    out.append(f"- Buck hot-loop parts (C6/C7/C8, U1, D3) span: {span:.1f} mm")
except Exception as e:
    out.append(f"- Buck hot-loop check skipped: {e}")
vsmall = sum(1 for t in b.GetTracks() if t.GetClass() == "PCB_VIA" and tomm(t.GetDrill()) < 0.2)
vip = 0
for t in b.GetTracks():
    if t.GetClass() == "PCB_VIA" and tomm(t.GetDrill()) < 0.2:
        for f in b.GetFootprints():
            for p in f.Pads():
                if p.GetNetCode() == t.GetNetCode() and p.HitTest(t.GetPosition()):
                    vip += 1; break
out.append(f"- Vias: {sum(1 for t in b.GetTracks() if t.GetClass() == 'PCB_VIA')} total; {vsmall} at 0.35/0.15 mm, of which {vip} are via-in-pad (need JLC epoxy fill + cap)")
open(os.path.join(HERE, "critical_nets.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
