"""Generate the Simantic scenario from the board's own netlist (design.py), so the
simulated wiring is the PCB's wiring, not a hand-typed copy of it.

For each simulated part we take the net on its chip-select / bus pins, find which
STM32 pin that net lands on, and derive the peripheral from the pin-map check.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", ".."))
import design
from pinmap_check import REQ

parts = {p["ref"]: p for p in design.PARTS}
net_to_mcu = {}
for port, net in design.MCU_PINS.items():
    net_to_mcu.setdefault(net, port)
# series resistors between MCU and part (R28 SPI1_SCK_MCU -> SPI1_SCK etc.)
series = {}
for p in design.PARTS:
    if p["lib"] == "Device:R" and len(p["pins"]) == 2:
        a, b = p["pins"]["1"], p["pins"]["2"]
        if a.endswith("_MCU") and not b.startswith("+"):
            series[b] = a


def mcu_pin(net):
    net = series.get(net, net)
    if net not in net_to_mcu:
        raise SystemExit(f"net {net} does not reach the MCU")
    return net_to_mcu[net]


def bus_of(net, kind):
    f = REQ[mcu_pin(net)]
    return f.split("_")[0].lower().replace("i2c", "i2c")


u20, u21, u22 = parts["U20"]["pins"], parts["U21"]["pins"], parts["U22"]["pins"]
spi_imu = bus_of(u20["13"], "SCK")          # ICM-45686 SCLK
spi_bmi = bus_of(u21["8"], "SCK")           # BMI088 SCK
i2c_baro = bus_of(u22["4"], "SDA")          # BMP581 SDA
sdo = u22["5"]
baro_addr = 0x47 if any(p["lib"] == "Device:R" and sdo in p["pins"].values() and "+3V3_SENS" in p["pins"].values()
                        for p in design.PARTS) else 0x46
can1 = REQ[mcu_pin(parts["U40"]["pins"]["1"])].split("_")[0].lower()
sd_bus = REQ[mcu_pin("SD_CMD")].split("_")[0].lower()
# the simulator variant: same board, SDMMC write-complete wait off (see run_simantic.command)
elf = "../../../PX4-Autopilot/build/dvntekim_fch743sim_default/dvntekim_fch743sim_default.elf"
yaml = f"""# GENERATED by gen_scenario.py from design.py (the PCB netlist). Do not edit by hand.
# Every bus, chip-select and address below is derived from the board's nets.
machines:
  fc:
    mcu: STM32H743VI
    elf: {elf}
    parts:
      - {{ name: card, type: sd-card, bus: {sd_bus}, size: 16MiB, image: card.img }}
      - {{ name: imu0, type: spi-device, bus: {spi_imu}, cs: {mcu_pin(u20['12'])}, script: peers/icm45686_peer.py }}
      - {{ name: acc1, type: spi-device, bus: {spi_bmi}, cs: {mcu_pin(u21['14'])}, script: peers/bmi088_accel_peer.py }}
      - {{ name: gyr1, type: spi-device, bus: {spi_bmi}, cs: {mcu_pin(u21['5'])}, script: peers/bmi088_gyro_peer.py }}
      - {{ name: baro, type: i2c-device, bus: {i2c_baro}, address: {baro_addr:#04x}, script: peers/bmp581_peer.py }}
      - {{ name: flow, type: can-node, script: peers/dronecan_nodestatus_peer.py }}
media:
  - type: can
    connect: [fc.{can1}, fc.flow]
timeout: 30
expect:
  - "NuttShell"
  - "icm45686 #0 on SPI bus {spi_imu[-1]}"
  - "bmi088"
  - "bmp581 #0 on I2C bus {i2c_baro[-1]} address {baro_addr:#04x}"
  - "logger started"
expect_absent:
  - "HardFault"
  - "PANIC"
"""
open(os.path.join(HERE, "scenario.yaml"), "w").write(yaml)
print(yaml)
